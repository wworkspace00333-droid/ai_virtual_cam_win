<#
Build the vcstudio-obs plugin for OBS Studio on Windows (x64) with MSVC.

No OBS SDK build is needed: import libraries are generated from the installed OBS's obs.dll and
obs-frontend-api.dll (dumpbin /exports -> .def -> lib), and the headers come from the obs-studio
source tree of the SAME version as the installed OBS (libobs/ and frontend/api/).

  scripts\build_obs_plugin_win.ps1 -Headers C:\src\obs-studio-33.0.0 [-ObsDir "C:\Program Files\obs-studio"]

Output: build\obs-plugin\win\vcstudio-obs.dll (install with the app's Input page, or copy to
%ProgramData%\obs-studio\plugins\vcstudio-obs\bin\64bit\).
Requires Visual Studio 2022 (Build Tools) with the C++ x64 toolset.
#>
param(
    [Parameter(Mandatory = $true)][string]$Headers,
    [string]$ObsDir = "C:\Program Files\obs-studio",
    [string]$Out = ""
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
if (-not $Out) { $Out = Join-Path $root "build\obs-plugin\win" }
New-Item -ItemType Directory -Force $Out | Out-Null
$bin = Join-Path $ObsDir "bin\64bit"
foreach ($f in "obs.dll", "obs-frontend-api.dll") {
    if (-not (Test-Path (Join-Path $bin $f))) { throw "$f not found in $bin (is OBS installed?)" }
}
foreach ($d in "libobs\obs-module.h", "frontend\api\obs-frontend-api.h") {
    if (-not (Test-Path (Join-Path $Headers $d))) { throw "$d not found under $Headers (obs-studio source tree)" }
}
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw "Visual Studio C++ x64 build tools not found" }
$vcvars = Join-Path $vs "VC\Auxiliary\Build\vcvars64.bat"

# obsconfig.h is generated by OBS's CMake; the plugin needs only the release/beta switches.
$gen = Join-Path $Out "gen"
New-Item -ItemType Directory -Force $gen | Out-Null
Set-Content -Encoding ascii (Join-Path $gen "obsconfig.h") "#pragma once`r`n#define OBS_RELEASE_CANDIDATE 0`r`n#define OBS_BETA 0`r`n"

$env:Path = "$(Split-Path $vswhere);$env:Path"     # vcvars64.bat looks vswhere.exe up on PATH

function Invoke-VS([string]$cmd) {
    $full = "call `"$vcvars`" >nul 2>nul && $cmd"
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"                # compiler notes on stderr are not failures
    & cmd.exe /c $full 2>&1 | ForEach-Object { "$_" }
    $code = $LASTEXITCODE
    $ErrorActionPreference = $prev
    if ($code -ne 0) { throw "failed ($code): $cmd" }
}

foreach ($name in "obs", "obs-frontend-api") {
    $dll = Join-Path $bin "$name.dll"
    $dump = Join-Path $Out "$name.exports.txt"
    Invoke-VS "dumpbin /nologo /exports `"$dll`" > `"$dump`""
    $names = Get-Content $dump | ForEach-Object {
        if ($_ -match '^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)') { $Matches[1] }
    }
    if (-not $names) { throw "no exports parsed from $dll" }
    $def = Join-Path $Out "$name.def"
    Set-Content -Encoding ascii $def (@("LIBRARY $name.dll", "EXPORTS") + $names)
    Invoke-VS "lib /nologo /def:`"$def`" /machine:x64 /out:`"$(Join-Path $Out "$name.lib")`""
}

$src = Join-Path $root "native\obs-plugin\vcstudio-obs.c"
$inc = "/I`"$gen`" /I`"$(Join-Path $Headers 'libobs')`" /I`"$(Join-Path $Headers 'frontend\api')`""
Invoke-VS ("cl /nologo /O2 /MD /W3 /std:c11 /D_CRT_SECURE_NO_WARNINGS $inc /LD `"$src`" /Fo`"$Out\\`" " +
           "/link /OUT:`"$(Join-Path $Out 'vcstudio-obs.dll')`" /IMPLIB:`"$(Join-Path $Out 'vcstudio-obs.lib')`" " +
           "`"$(Join-Path $Out 'obs.lib')`" " +
           "`"$(Join-Path $Out 'obs-frontend-api.lib')`"")
Write-Host "OK $(Join-Path $Out 'vcstudio-obs.dll')"
